//! Embedded Ring-3 test program for the signal-return register contract.
//!
//! Verifies the requirement of POSIX.1-2017 sigaction(2) that the interrupted
//! context is restored when a signal handler returns, for the two registers
//! the x86-64 System V psABI §3.2.3 puts in the saved general-register set but
//! which the SYSCALL/SYSRETQ pair treats as scratch: RCX and R11.
//!
//! The program loads a sentinel into each, faults on an unmapped page, and —
//! after the SIGSEGV handler maps the page and returns — checks that both
//! registers survived and that the `ucontext_t` the handler was handed agreed
//! with them.  It exits with a code naming the first divergence:
//!
//! | exit | meaning                                             |
//! |------|-----------------------------------------------------|
//! | 0    | RCX, R11 and the ucontext all preserved             |
//! | 1    | RCX clobbered across the handler return             |
//! | 2    | R11 clobbered across the handler return             |
//! | 3    | ucontext gregs[REG_RCX] disagreed with the sentinel |
//! | 4    | ucontext gregs[REG_R11] disagreed with the sentinel |
//! | 5    | the faulting store was not retried successfully     |
//! | 6    | rt_sigaction(2) failed                              |
//!
//! Single R+X PT_LOAD at 0x400000; entry 0x400078.  Uses the Linux syscall
//! numbering (rt_sigaction 13, mmap 9, exit 60), so the process must be
//! created with the Linux personality.
//!
//! # Source
//!
//!     .intel_syntax noprefix
//!     .text
//!     .globl _start
//!
//! /* One R+X PT_LOAD, no writable data in the image (the kernel enforces W^X on
//!  * PT_LOAD).  Scratch lives on the stack and in the page the handler maps:
//!  *   [0x30000000] = the byte the faulting store writes
//!  *   [0x30000008] = ucontext gregs[REG_RCX] as the handler saw it
//!  *   [0x30000010] = ucontext gregs[REG_R11] as the handler saw it
//!  * Every code reference is RIP-relative, so there are no relocations. */
//!
//!     .equ SCRATCH, 0x30000000
//!
//! _start:
//!     /* struct kernel_sigaction { handler, flags, restorer, mask } on the stack */
//!     sub     rsp, 32
//!     lea     rcx, [rip + handler]
//!     mov     [rsp], rcx                  /* sa_handler                     */
//!     mov     qword ptr [rsp + 8],  4     /* sa_flags = SA_SIGINFO          */
//!     mov     qword ptr [rsp + 16], 0     /* sa_restorer = 0 → kernel tramp */
//!     mov     qword ptr [rsp + 24], 0     /* sa_mask = {}                   */
//!
//!     /* rt_sigaction(SIGSEGV, &act, NULL, sizeof(sigset_t)) */
//!     mov     rsi, rsp
//!     mov     eax, 13
//!     mov     edi, 11
//!     xor     edx, edx
//!     mov     r10d, 8
//!     syscall
//!     add     rsp, 32
//!     test    rax, rax
//!     js      fail_sigaction
//!
//!     /* Load the sentinels and take a fault with them live. */
//!     movabs  rcx, 0x0123456789ABCDEF
//!     movabs  r11, 0x0FEDCBA987654321
//!     mov     ebx, SCRATCH
//!     mov     byte ptr [rbx], 0x5A        /* SIGSEGV; handler maps the page */
//!
//!     /* Back from the handler via sigreturn.  RCX/R11 must be intact. */
//!     movabs  rax, 0x0123456789ABCDEF
//!     cmp     rcx, rax
//!     jne     fail_rcx
//!     movabs  rax, 0x0FEDCBA987654321
//!     cmp     r11, rax
//!     jne     fail_r11
//!
//!     /* The ucontext handed to the handler must have reported the same. */
//!     movabs  rax, 0x0123456789ABCDEF
//!     cmp     [rbx + 8], rax
//!     jne     fail_uc_rcx
//!     movabs  rax, 0x0FEDCBA987654321
//!     cmp     [rbx + 16], rax
//!     jne     fail_uc_r11
//!
//!     /* And the faulting store must have been retried successfully. */
//!     cmp     byte ptr [rbx], 0x5A
//!     jne     fail_store
//!
//!     xor     edi, edi                    /* exit 0 — everything preserved  */
//!     jmp     do_exit
//!
//! fail_rcx:       mov edi, 1
//!                 jmp do_exit
//! fail_r11:       mov edi, 2
//!                 jmp do_exit
//! fail_uc_rcx:    mov edi, 3
//!                 jmp do_exit
//! fail_uc_r11:    mov edi, 4
//!                 jmp do_exit
//! fail_store:     mov edi, 5
//!                 jmp do_exit
//! fail_sigaction: mov edi, 6
//! do_exit:
//!     mov     eax, 60                     /* exit                           */
//!     syscall
//!     hlt
//!
//! /* void handler(int signo, siginfo_t *info, ucontext_t *uc)
//!  * uc->uc_mcontext.gregs starts at offset 40; REG_R11 = 3, REG_RCX = 14. */
//! handler:
//!     mov     rax, [rdx + 152]            /* gregs[REG_RCX]                 */
//!     push    rax
//!     mov     rax, [rdx + 64]             /* gregs[REG_R11]                 */
//!     push    rax
//!     /* mmap(SCRATCH, 4096, RW, PRIVATE|ANON|FIXED, -1, 0) so the retry of
//!      * the faulting store succeeds and the handler can simply return. */
//!     mov     eax, 9
//!     mov     edi, SCRATCH
//!     mov     esi, 4096
//!     mov     edx, 3
//!     mov     r10d, 0x32
//!     mov     r8, -1
//!     xor     r9d, r9d
//!     syscall
//!     pop     rcx
//!     mov     [SCRATCH + 16], rcx         /* saved gregs[REG_R11]           */
//!     pop     rcx
//!     mov     [SCRATCH + 8], rcx          /* saved gregs[REG_RCX]           */
//!     ret

